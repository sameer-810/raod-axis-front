"""
Trace the client's logo into the SVG files the product uses.

    python scripts/trace-logo.py

Reads public/brand/source/roadaxis-logo-on-dark.jpg (white letters, a red X,
a flat dark ground) and writes:

    public/brand/roadaxis-wordmark-on-light.svg   ink letters, red X
    public/brand/roadaxis-wordmark-on-dark.svg    white letters, red X
    public/brand/roadaxis-mark.svg                the X alone on the ink square
    public/favicon.svg                            the same mark
    src/shared/components/logoPaths.ts            the paths, for Logo.tsx

Needs Pillow, numpy and potracer (pip install potracer). Edit the source
picture, not the outputs.
"""
from PIL import Image
import numpy as np
import potrace

SRC = "public/brand/source/roadaxis-logo-on-dark.jpg"
RED, INK = "#FA0101", "#0E1621"

im = np.asarray(Image.open(SRC).convert("RGB")).astype(int)
r, g, b = im[..., 0], im[..., 1], im[..., 2]
lum = (r + g + b) / 3
red = (r > 140) & (g < 120) & (b < 120)
white = (lum > 128) & ~red


def trace(mask, dp=1):
    # potracer reads a nonzero pixel as paper, so the shape goes in as zeros.
    path = potrace.Bitmap(~mask).trace(
        turdsize=3,
        turnpolicy=potrace.POTRACE_TURNPOLICY_MINORITY,
        alphamax=1.0,
        opticurve=True,
        opttolerance=0.3,
    )
    f = lambda v: f"{round(v, dp):g}"
    out = []
    for c in path:
        s = c.start_point
        d = f"M{f(s.x)} {f(s.y)}"
        for seg in c.segments:
            if seg.is_corner:
                d += f"L{f(seg.c.x)} {f(seg.c.y)}L{f(seg.end_point.x)} {f(seg.end_point.y)}"
            else:
                d += (
                    f"C{f(seg.c1.x)} {f(seg.c1.y)} {f(seg.c2.x)} {f(seg.c2.y)} "
                    f"{f(seg.end_point.x)} {f(seg.end_point.y)}"
                )
        out.append(d + "Z")
    return "".join(out)


letters, x = trace(white), trace(red)
ys, xs = np.where(white | red)
x0, y0, x1, y1 = xs.min() - 4, ys.min() - 4, xs.max() + 5, ys.max() + 5
vb = f"{x0} {y0} {x1 - x0} {y1 - y0}"


def wordmark(fill):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" role="img" aria-label="RoadAxis">'
        f'<path fill="{fill}" d="{letters}"/><path fill="{RED}" d="{x}"/></svg>'
    )


open("public/brand/roadaxis-wordmark-on-light.svg", "w").write(wordmark(INK))
open("public/brand/roadaxis-wordmark-on-dark.svg", "w").write(wordmark("#FFFFFF"))

rys, rxs = np.where(red)
rx0, ry0, rx1, ry1 = rxs.min(), rys.min(), rxs.max() + 1, rys.max() + 1
w, h = rx1 - rx0, ry1 - ry0
scale = 22 / max(w, h)
tx, ty = (32 - w * scale) / 2 - rx0 * scale, (32 - h * scale) / 2 - ry0 * scale
transform = f"translate({tx:.3f} {ty:.3f}) scale({scale:.5f})"
mark = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">'
    f'<rect width="32" height="32" rx="7" fill="{INK}"/>'
    f'<path fill="{RED}" transform="{transform}" d="{x}"/></svg>'
)
open("public/brand/roadaxis-mark.svg", "w").write(mark)
open("public/favicon.svg", "w").write(mark)

open("src/shared/components/logoPaths.ts", "w").write(
    "// Generated by scripts/trace-logo.py from the client's logo\n"
    "// (public/brand/source/roadaxis-logo-on-dark.jpg, 15 October 2026).\n"
    "// Regenerate rather than edit: the same trace feeds public/brand/*.svg and\n"
    "// the favicon.\n"
    f'export const WORDMARK_VIEWBOX = "{vb}";\n'
    f'export const WORDMARK_LETTERS = "{letters}";\n'
    f'export const WORDMARK_X = "{x}";\n'
    f'export const WORDMARK_RED = "{RED}";\n'
    f'export const MARK_X_TRANSFORM = "{transform}";\n'
)
print("viewBox", vb, "| letter outlines", letters.count("Z"), "| X outlines", x.count("Z"))
